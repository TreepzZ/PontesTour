// Função principal de tradução
function setLanguage(lang) {
    document.querySelectorAll('[data-key]').forEach(element => {
        const key = element.getAttribute('data-key');
        
        // Trata a exceção do título com destaque (highlight)
        if (key === 'destinations-title' || key === 'cta-title') {
             // O título (ex: DESTINOS PRINCIPAIS) é dividido em duas partes: tag normal e span (highlight)
            const highlightSpan = element.querySelector('.highlight');
            
            // Verifica se a parte normal (fora do span) existe na tradução
            if (translations[key] && translations[key][lang]) {
                // Se houver um destaque (span), o texto vai para o span, se não, vai para o elemento pai
                if (highlightSpan && translations[`${key}-highlight`]) {
                    // O texto principal é inserido no elemento pai
                    element.innerHTML = translations[key][lang] + ' <span class="highlight">' + translations[`${key}-highlight`][lang] + '</span>';
                } else {
                    // Se for um título simples, o texto vai direto
                     element.textContent = translations[key][lang];
                }
            }
        } else {
             // Tratamento normal para os demais textos (p, h3, a, etc.)
            if (translations[key] && translations[key][lang]) {
                element.textContent = translations[key][lang];
            }
        }
    });

    // Salva a preferência no armazenamento local
    localStorage.setItem('language', lang);

    // Atualiza a classe 'active' nos botões
    document.querySelectorAll('.lang-option').forEach(btn => {
        btn.classList.remove('active');
        if (btn.getAttribute('data-lang') === lang) {
            btn.classList.add('active');
        }
    });
}

// Inicialização: carrega o idioma salvo ou usa o padrão (PT)
document.addEventListener('DOMContentLoaded', () => {
    // Tenta carregar o idioma salvo. Se não houver, usa 'pt'.
    const savedLang = localStorage.getItem('language') || 'pt';
    setLanguage(savedLang);

    // Adiciona evento de clique aos botões
    document.querySelectorAll('.lang-option').forEach(button => {
        button.addEventListener('click', (e) => {
            e.preventDefault(); // Evita que a página recarregue
            const newLang = button.getAttribute('data-lang');
            setLanguage(newLang);
        });
    });
});

