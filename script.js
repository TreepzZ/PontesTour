// --- FUNÇÃO PARA INICIALIZAR O MAPA DE LOCALIZAÇÃO DO USUÁRIO ---
function initializeUserMap() {
    const mapContainer = document.getElementById('user-map-container');
    
    // Verifica se a geolocalização é suportada pelo navegador
    if (navigator.geolocation) {
        mapContainer.innerHTML = '<p style="color: #666;">Buscando sua localização...</p>';
        
        // Solicita a localização
        navigator.geolocation.getCurrentPosition(
            (position) => {
                const lat = position.coords.latitude;
                const lng = position.coords.longitude;
                
                // Em um ambiente real, o mapa do Google Maps seria injetado aqui.
                // Usaremos um link de mapa estático de exemplo para simulação:
                const mapUrl = `http://maps.google.com/maps?q=${lat},${lng}&z=15&output=embed`;
                
                mapContainer.innerHTML = `
                    <p style="font-size: 1rem; color: #1f2c4c; margin-bottom: 10px;">
                        Coordenadas encontradas!
                    </p>
                    <iframe 
                        width="100%" 
                        height="350px" 
                        frameborder="0" 
                        style="border:0; border-radius: 8px;" 
                        referrerpolicy="no-referrer-when-downgrade" 
                        src="${mapUrl}" 
                        allowfullscreen>
                    </iframe>
                `;
            },
            (error) => {
                let errorMessage = 'Não foi possível obter sua localização. Verifique as permissões do seu navegador.';
                if (error.code === error.PERMISSION_DENIED) {
                    errorMessage = 'Acesso à localização negado. Por favor, habilite o GPS.';
                }
                mapContainer.innerHTML = `<p style="color: red; font-weight: 600;">⚠️ ${errorMessage}</p>`;
            }
        );
    } else {
        mapContainer.innerHTML = '<p style="color: red;">Seu navegador não suporta geolocalização.</p>';
    }
}

